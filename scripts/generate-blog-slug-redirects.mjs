#!/usr/bin/env node
/**
 * Generates 301 redirects from legacy long blog slugs to short slugs.
 * Run: node scripts/generate-blog-slug-redirects.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BLOG_LEGACY_SLUG_REDIRECTS } from './blog-slug-migrations.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const MIDDLEWARE_OUT = join(ROOT, 'functions', 'blog-slug-redirects.js');
const REDIRECTS_FILE = join(ROOT, 'public', '_redirects');
const BEGIN = '# BEGIN AUTO-GENERATED blog slug redirects';
const END = '# END AUTO-GENERATED blog slug redirects';

/** @type {Record<string, string>} */
const redirects = {};

for (const [legacySlug, shortSlug] of Object.entries(BLOG_LEGACY_SLUG_REDIRECTS)) {
	const to = `/blog/${shortSlug}/`;
	redirects[`/blog/${legacySlug}/`] = to;
	redirects[`/blog/${legacySlug}`] = to;
}

const middlewareBody = `/** AUTO-GENERATED by scripts/generate-blog-slug-redirects.mjs — do not edit by hand. */
export const BLOG_SLUG_REDIRECTS = ${JSON.stringify(redirects, null, '\t')};
`;

writeFileSync(MIDDLEWARE_OUT, middlewareBody, 'utf8');

const redirectLines = Object.entries(redirects).map(([from, to]) => `${from} ${to} 301`);
const generatedBlock = [BEGIN, ...redirectLines, END, ''].join('\n');

let redirectsFile = readFileSync(REDIRECTS_FILE, 'utf8');
const beginIdx = redirectsFile.indexOf(BEGIN);
const endIdx = redirectsFile.indexOf(END);

if (beginIdx >= 0 && endIdx > beginIdx) {
	redirectsFile = `${redirectsFile.slice(0, beginIdx)}${generatedBlock}${redirectsFile.slice(endIdx + END.length).replace(/^\n*/, '')}`;
} else {
	redirectsFile = `${redirectsFile.replace(/\n?$/, '\n\n')}${generatedBlock}`;
}

writeFileSync(REDIRECTS_FILE, redirectsFile, 'utf8');
console.log(`Wrote ${Object.keys(redirects).length} blog slug redirects → ${MIDDLEWARE_OUT}`);
