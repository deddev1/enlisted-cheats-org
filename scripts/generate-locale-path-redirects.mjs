#!/usr/bin/env node
/**
 * Generates functions/locale-path-redirects.js from scripts/i18n-data/paths.mjs.
 * Run after changing localized slugs or thin-landing targets.
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { localizedSlugs } from './i18n-data/paths.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'functions', 'locale-path-redirects.js');

/** Keep in sync with thinLandingCanonicalTargets in src/data/i18n/routing.ts */
const THIN_LANDING_TARGETS = {
	undetected: 'hacks',
	'cheats-2026': 'hacks',
	'eac-bypass': 'hacks',
	'cheat-download': 'pricing',
	'mod-menu': 'features',
	'soft-aim': 'enlisted-aimbot',
	'best-cheats': 'hacks',
	'aimbot-hack': 'enlisted-aimbot',
	'esp-hack': 'enlisted-esp',
	'unlock-all': 'features',
};

const localeCodes = Object.keys(localizedSlugs.home).filter((code) => code !== 'en');

function localizedPath(pageId, locale) {
	const slug = localizedSlugs[pageId]?.[locale];
	return slug ? `/${locale}/${slug}/` : `/${locale}/`;
}

const redirects = {};

for (const [thinId, canonicalId] of Object.entries(THIN_LANDING_TARGETS)) {
	for (const locale of localeCodes) {
		const from = localizedPath(thinId, locale);
		const to = localizedPath(canonicalId, locale);
		if (from === to) continue;
		redirects[from] = to;
		redirects[from.replace(/\/$/, '')] = to;
	}
}

const body = `/** AUTO-GENERATED by scripts/generate-locale-path-redirects.mjs — do not edit by hand. */
export const LOCALE_PATH_REDIRECTS = ${JSON.stringify(redirects, null, '\t')};
`;

await writeFile(OUT, body, 'utf8');
console.log(`Wrote ${Object.keys(redirects).length} locale path redirects → ${path.relative(ROOT, OUT)}`);
